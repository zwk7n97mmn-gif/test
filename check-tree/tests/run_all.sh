#!/usr/bin/env bash
# 全テストを通す。外部への通信はしない。
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$HERE/.."
FAILED=""

echo "=============================================================="
echo " ツリー照合の動き"
echo "=============================================================="
python3 "$HERE/test_check_tree.py" || FAILED="$FAILED
  - 動きのテスト"

echo
echo "=============================================================="
echo " 自分自身の README を照合する"
echo "=============================================================="
python3 "$ROOT/check_tree.py" || FAILED="$FAILED
  - 自分自身の照合"

echo
echo "=============================================================="
if [ -n "$FAILED" ]; then
  echo "失敗したテストがあります:$FAILED"
  exit 1
fi
echo "すべてのテストが通りました。"
